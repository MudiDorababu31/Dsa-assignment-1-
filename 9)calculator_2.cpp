#include<iostream>
using namespace std;
 
int main() {
    long long m;
    long long n;
    cin >> m; 
    cin >> n;
	cout << m << " + " <<n <<" = "<< (m + n) << endl;
	cout <<'\n';
	cout << m << " - " <<n <<" = "<< (m - n) << endl;
	cout <<'\n';
	cout << m << " * " <<n <<" = "<< (m * n) << endl;
	cout <<'\n';
	cout << m << " / " <<n <<" = "<< (m / n) << endl;
	cout <<'\n';
	cout << m << " % " <<n <<" = "<< (m % n) << endl;
	
	 
}